"""Load the engine version from Build/Version.json and the build number and branch of generate.

The major, minor and patch numbers change rarely and are defined for every module. The build number
and branch change with every CI build, so they are defined only in MarlinBuildVersion.h; defining
them for every module would recompile everything, and miss the cache, on each build.
"""

import json
import re
from dataclasses import dataclass
from pathlib import Path

VERSION_HEADER = "MarlinBuildVersion.h"
_BRANCH = re.compile(r"[A-Za-z0-9._/+-]*")


class VersionError(Exception):
    """Raised for an invalid Version.json, build number or branch."""


@dataclass(frozen=True)
class EngineVersion:
    """The engine version; *build* is the CI build number, 0 for local builds."""

    major: int
    minor: int
    patch: int
    build: int = 0
    branch: str = ""

    @property
    def semver(self) -> str:
        return f"{self.major}.{self.minor}.{self.patch}"

    @property
    def full(self) -> str:
        return f"{self.semver}+{self.build}" if self.build else self.semver

    def global_definitions(self) -> list[str]:
        """Return the definitions every module gets."""
        return [
            f"MARLIN_VERSION_MAJOR={self.major}",
            f"MARLIN_VERSION_MINOR={self.minor}",
            f"MARLIN_VERSION_PATCH={self.patch}",
        ]

    def header_lines(self) -> list[str]:
        """Return the lines of MarlinBuildVersion.h."""
        return [
            "// Generated by `marlin generate`. Do not edit.",
            "// Changes with every CI build: include it only where needed.",
            "#pragma once",
            f"#define MARLIN_VERSION_BUILD {self.build}",
            f'#define MARLIN_VERSION_BRANCH "{self.branch}"',
            f'#define MARLIN_VERSION_STRING "{self.full}"',
        ]

    def to_dict(self) -> dict[str, int | str]:
        return {
            "major": self.major,
            "minor": self.minor,
            "patch": self.patch,
            "build": self.build,
            "branch": self.branch,
        }


def load_version(path: Path, build: int | None, branch: str | None) -> EngineVersion:
    """Return the version in *path* with *build* and *branch*; a missing file means 0.0.0."""
    data: dict[str, object] = {}
    if path.is_file():
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as error:
            raise VersionError(f"{path}: {error}") from error
        if not isinstance(data, dict):
            raise VersionError(f"{path}: expected an object")
    unknown = set(data) - {"major", "minor", "patch"}
    if unknown:
        raise VersionError(f"{path}: unknown key(s) {', '.join(sorted(unknown))}")
    parts = []
    for key in ("major", "minor", "patch"):
        value = data.get(key, 0)
        if isinstance(value, bool) or not isinstance(value, int) or value < 0:
            raise VersionError(f"{path}: '{key}' must be a non-negative integer")
        parts.append(value)
    if build is not None and build < 0:
        raise VersionError("--build-id must be a non-negative integer")
    branch = branch or ""
    if not _BRANCH.fullmatch(branch):
        raise VersionError(f"--branch '{branch}' may only contain letters, digits and . _ / + -")
    return EngineVersion(parts[0], parts[1], parts[2], build or 0, branch)
