MARLIN_TEST(Crypto, Aes256CtrNistSp80038aF55)
{
    // NIST SP 800-38A, F.5.5 CTR-AES256.Encrypt.
    const uint8 key[32] = {0x60, 0x3d, 0xeb, 0x10, 0x15, 0xca, 0x71, 0xbe, 0x2b, 0x73, 0xae,
                           0xf0, 0x85, 0x7d, 0x77, 0x81, 0x1f, 0x35, 0x2c, 0x07, 0x3b, 0x61,
                           0x08, 0xd7, 0x2d, 0x98, 0x10, 0xa3, 0x09, 0x14, 0xdf, 0xf4};
    const uint8 counter[16] = {0xf0, 0xf1, 0xf2, 0xf3, 0xf4, 0xf5, 0xf6, 0xf7,
                               0xf8, 0xf9, 0xfa, 0xfb, 0xfc, 0xfd, 0xfe, 0xff};
    const uint8 plain[64] = {0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96, 0xe9, 0x3d, 0x7e, 0x11, 0x73,
                             0x93, 0x17, 0x2a, 0xae, 0x2d, 0x8a, 0x57, 0x1e, 0x03, 0xac, 0x9c, 0x9e, 0xb7,
                             0x6f, 0xac, 0x45, 0xaf, 0x8e, 0x51, 0x30, 0xc8, 0x1c, 0x46, 0xa3, 0x5c, 0xe4,
                             0x11, 0xe5, 0xfb, 0xc1, 0x19, 0x1a, 0x0a, 0x52, 0xef, 0xf6, 0x9f, 0x24, 0x45,
                             0xdf, 0x4f, 0x9b, 0x17, 0xad, 0x2b, 0x41, 0x7b, 0xe6, 0x6c, 0x37, 0x10};
    const uint8 cipher[64] = {0x60, 0x1e, 0xc3, 0x13, 0x77, 0x57, 0x89, 0xa5, 0xb7, 0xa7, 0xf5, 0x04, 0xbb,
                              0xf3, 0xd2, 0x28, 0xf4, 0x43, 0xe3, 0xca, 0x4d, 0x62, 0xb5, 0x9a, 0xca, 0x84,
                              0xe9, 0x90, 0xca, 0xca, 0xf5, 0xc5, 0x2b, 0x09, 0x30, 0xda, 0xa2, 0x3d, 0xe9,
                              0x4c, 0xe8, 0x70, 0x17, 0xba, 0x2d, 0x84, 0x98, 0x8d, 0xdf, 0xc9, 0xc5, 0x8d,
                              0xb6, 0x7a, 0xad, 0xa6, 0x13, 0xc2, 0xdd, 0x08, 0x45, 0x79, 0x41, 0xa6};
    uint8 data[64];
    MemCopy(data, plain, sizeof(data));
    MARLIN_EXPECT(PlatformCrypto::Aes256Ctr(Span<const uint8>(key), counter, Span<uint8>(data)));
    MARLIN_EXPECT(MemCompare(data, cipher, sizeof(data)) == 0);
    // Decrypting is the same operation; an odd length exercises the partial last block.
    MARLIN_EXPECT(PlatformCrypto::Aes256Ctr(Span<const uint8>(key), counter, Span<uint8>(data, 37)));
    MARLIN_EXPECT(MemCompare(data, plain, 37) == 0);
    MARLIN_EXPECT(!PlatformCrypto::Aes256Ctr(Span<const uint8>(key, 16), counter, Span<uint8>(data)));
}

MARLIN_TEST(Crypto, Sha256Fips1802)
{
    // FIPS 180-2, appendix B.1: "abc".
    const uint8 text[3] = {'a', 'b', 'c'};
    const uint8 expected[32] = {0xba, 0x78, 0x16, 0xbf, 0x8f, 0x01, 0xcf, 0xea, 0x41, 0x41, 0x40,
                                0xde, 0x5d, 0xae, 0x22, 0x23, 0xb0, 0x03, 0x61, 0xa3, 0x96, 0x17,
                                0x7a, 0x9c, 0xb4, 0x10, 0xff, 0x61, 0xf2, 0x00, 0x15, 0xad};
    uint8 digest[PlatformCrypto::Sha256Size];
    MARLIN_EXPECT(PlatformCrypto::Sha256(Span<const uint8>(text), digest));
    MARLIN_EXPECT(MemCompare(digest, expected, sizeof(digest)) == 0);
}

MARLIN_TEST(Crypto, EcdsaP256SignsAndVerifies)
{
    uint8 privateKey[PlatformCrypto::EcdsaP256PrivateKeySize];
    MARLIN_REQUIRE(PlatformCrypto::EcdsaP256Generate(privateKey));
    const Span<const uint8> publicKey(privateKey, PlatformCrypto::EcdsaP256PublicKeySize);
    uint8 digest[PlatformCrypto::Sha256Size] = {1, 2, 3};
    uint8 signature[PlatformCrypto::EcdsaP256SignatureSize];
    MARLIN_REQUIRE(PlatformCrypto::EcdsaP256Sign(Span<const uint8>(privateKey), digest, signature));
    MARLIN_EXPECT(PlatformCrypto::EcdsaP256Verify(publicKey, digest, Span<const uint8>(signature)));
    digest[0] ^= 1;
    MARLIN_EXPECT(!PlatformCrypto::EcdsaP256Verify(publicKey, digest, Span<const uint8>(signature)));
    MARLIN_EXPECT(!PlatformCrypto::EcdsaP256Verify(publicKey.Slice(0, 32), digest, Span<const uint8>(signature)));
}
